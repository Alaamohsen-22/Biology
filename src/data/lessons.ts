// Separate banks: 5 independent prerequisite items and 7 objective-aligned post items per lesson.
export function bank(
  lesson: Lesson,
  kind: "pre" | "post",
  retry = 0,
): Question[] {
  const chosen =
    kind === "pre"
      ? lesson.questions.slice(0, 5)
      : retry % 2 === 1
        ? parallel[lesson.id]
        : lesson.questions.slice(5);
  return chosen.map((item, i) => {
    const offset = (retry + i) % item.options.length;
    return {
      ...item,
      id: `${kind}-${item.id}-${retry}`,
      text: item.text,
      options: [
        ...item.options.slice(offset),
        ...item.options.slice(0, offset),
      ],
      answer:
        (item.answer - offset + item.options.length) % item.options.length,
    };
  });
}
